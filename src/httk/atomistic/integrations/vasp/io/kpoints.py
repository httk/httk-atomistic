"""Writer for VASP line-mode KPOINTS files."""

import io
import os
from collections.abc import Mapping, Sequence
from fractions import Fraction
from typing import Any

from httk.core import FracVector


def write_line_mode_kpoints(
    destination: str | os.PathLike[str] | io.TextIOBase,
    points: Mapping[str, Any],
    path: Sequence[tuple[str, str]],
    *,
    divisions: int = 40,
    comment: str = "Band-structure path generated by httk",
) -> None:
    """Write a VASP line-mode KPOINTS file for a band-structure path.

    Coordinates are reciprocal fractional coordinates of the cell the path belongs to (for
    ``band_path``, ``result.structure``). The written decimals are a rounded presentation of the
    exact points. VASP line mode uses one point count, ``divisions``, for every segment.

    :param destination: Filesystem path or open text stream; a stream is not closed.
    :param points: Mapping from label to reciprocal fractional coordinates.
    :param path: Ordered ``(start, end)`` label pairs; each pair becomes one line segment.
    :param divisions: Number of k-points per segment (at least 2).
    :param comment: First line of the file.
    :raises ValueError: If the path, labels, points, comment or divisions cannot be written.
    """
    if type(divisions) is not int or divisions < 2:
        raise ValueError("divisions must be an int of at least 2.")
    if "\n" in comment or "\r" in comment:
        raise ValueError("comment must not contain a line break.")
    if not path:
        raise ValueError("path must contain at least one segment.")
    segments = []
    for segment in path:
        try:
            n = len(segment)
        except TypeError:
            n = None
        if isinstance(segment, str) or n != 2:
            raise ValueError(f"path segment {segment!r} is not a (start, end) pair.")
        lines = []
        for label in segment:
            if not isinstance(label, str) or not label or any(c in label for c in "!\n\r"):
                raise ValueError(f"invalid label {label!r}: must be non-empty without '!' or line breaks.")
            if label not in points:
                raise ValueError(f"label {label!r} is missing from points.")
            try:
                fractions = FracVector(points[label]).to_fractions()
            except (TypeError, ValueError):
                fractions = []
            if len(fractions) != 3 or not all(isinstance(f, Fraction) for f in fractions):
                raise ValueError(f"point {label!r} must have exactly three coordinates.")
            lines.append("".join(f"{format(f, '.12f'):>16}" for f in fractions) + f" ! {label}")
        segments.append("\n".join(lines))
    text = f"{comment}\n{divisions}\nLine-mode\nReciprocal\n" + "\n\n".join(segments) + "\n"
    if isinstance(destination, (str, os.PathLike)):
        with open(destination, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    else:
        destination.write(text)
