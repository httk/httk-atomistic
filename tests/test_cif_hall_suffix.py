"""Hall symbols with Hall's change-of-basis suffix (``P 2yb (z,x,y)``, ``P 61 2 (0 0 5)``)."""

import logging
from collections.abc import Mapping
from fractions import Fraction
from pathlib import Path
from typing import Any

import pytest
from httk.core import FracVector, load

from httk.atomistic import data
from httk.atomistic.cif_structures import _declared_settings, cif_setting
from httk.atomistic.io.cif.cif_parser import hall_setting
from httk.atomistic.symmetry.affine_operation import AffineOperation
from httk.atomistic.symmetry.setting_transform import SettingTransform
from httk.atomistic.symmetry.spacegroup import Spacegroup
from httk.atomistic.symmetry.xyz import operation_from_xyz


def _tabulated(record: Mapping[str, Any]) -> frozenset[AffineOperation]:
    return frozenset(AffineOperation.from_record(entry).wrapped() for entry in record["symops"])


def _closure(generators: list[str]) -> frozenset[AffineOperation]:
    group = {AffineOperation.identity()}
    frontier = list(group)
    while frontier:
        current = frontier.pop()
        for generator in generators:
            product = (operation_from_xyz(generator) * current).wrapped()
            if product not in group:
                group.add(product)
                frontier.append(product)
    return frozenset(group)


@pytest.mark.parametrize(
    ("hall_entry", "generators", "twelfths"),
    [
        ("p_31_2_(0_0_4)", ["-y,x-y,z+1/3", "-y,-x,-z"], 4),
        ("p_32_2_(0_0_2)", ["-y,x-y,z+2/3", "-y,-x,-z"], 2),
        ("p_61_2_(0_0_5)", ["x-y,x,z+1/6", "-y,-x,-z"], 5),
        ("p_65_2_(0_0_1)", ["x-y,x,z+5/6", "-y,-x,-z"], 1),
        ("p_62_2_(0_0_4)", ["x-y,x,z+1/3", "-y,-x,-z"], 4),
        ("p_64_2_(0_0_2)", ["x-y,x,z+2/3", "-y,-x,-z"], 2),
    ],
)
def test_the_tabulated_origin_shift_suffixes_pin_v_w_v_inverse(
    hall_entry: str, generators: list[str], twelfths: int
) -> None:
    """The six tabulated suffixed symbols fix the convention: ``W' = V W V^-1``, ``V = (I | v/12)``.

    The base groups are generated by hand from Hall's rules (``N_k`` screw along c, the
    following 2 along a-b), independently of the tables. The opposite convention fails.
    """
    base = _closure(generators)
    shift = AffineOperation(FracVector.eye((3, 3)), [0, 0, Fraction(twelfths, 12)])
    tabulated = _tabulated(data.spacegroup_setting(hall_entry=hall_entry))
    assert frozenset(operation.conjugated_by(shift).wrapped() for operation in base) == tabulated
    assert frozenset(operation.conjugated_by(shift.inverse()).wrapped() for operation in base) != tabulated


def test_every_tabulated_hall_symbol_declares_exactly_its_setting() -> None:
    """The fast path: a symbol tabulated as written names its record, whatever its translations."""
    for record in data.spacegroup_settings():
        settings, _ = _declared_settings({"space_group_name_hall": record["hall"]})
        assert settings == [record], record["hall"]


def test_every_tabulated_setting_is_its_standard_hall_symbol_with_its_change_of_basis() -> None:
    """Standard Hall symbol + the setting's tabulated transform as a suffix names that setting.

    Pure origin shifts in twelfths are written in the shorthand. The seven rhombohedral-axes
    transforms (``det == 3``) change the cell and are refused.
    """
    shorthand = explicit = refused = 0
    for record in data.spacegroup_settings():
        standard = data.standard_spacegroup_setting(record["it_number"])
        if record["hall_entry"] == standard["hall_entry"]:
            continue
        change = SettingTransform.from_hall_entry(record["hall_entry"]).operation
        if change.determinant() != 1:
            with pytest.raises(ValueError, match="unimodular"):
                hall_setting(f"{standard['hall']} ({change.to_xyz()})")
            refused += 1
            continue
        twelfths = [value * 12 for value in change.vector.to_fractions()]
        if change.matrix == FracVector.eye((3, 3)) and all(value.denominator == 1 for value in twelfths):
            suffix = " ".join(str(value.numerator) for value in twelfths)
            shorthand += 1
        else:
            suffix = change.to_xyz()
            explicit += 1
        assert hall_setting(f"{standard['hall']} ({suffix})") is record, record["hall"]
    assert (shorthand, explicit, refused) == (23, 267, 7)


def test_whitespace_is_normalized_before_the_table_lookup() -> None:
    assert hall_setting("P 31 2 (0  0 4)") is data.spacegroup_setting(hall_entry="p_31_2_(0_0_4)")
    assert hall_setting("  -C  2yc ") is data.spacegroup_setting(hall_entry="-c_2yc")


@pytest.mark.parametrize(
    "written",
    [
        "P 2yb (z,x)",
        "P 2yb (x,x,z)",
        "P 2yb (1/2x,y,z)",
        "P 2yb (0 0)",
        "P 2yb (0,0,1)",
        "P 2xa (2x,y,z)",
        "P 3 (2x,y,z)",
    ],
)
def test_unusable_suffixes_are_rejected(written: str) -> None:
    with pytest.raises(ValueError, match="neither an origin shift in twelfths .* nor a unimodular integer"):
        hall_setting(written)
    with pytest.raises(ValueError, match="names no known space-group setting"):
        _declared_settings({"space_group_name_hall": written})


@pytest.mark.parametrize("written", ["P 9 (x,y,z)", "P 2yb (0 0 1)"])
def test_unknown_bases_and_suffixes_onto_no_tabulated_setting_are_unknown(written: str) -> None:
    """``P 2yb (0 0 1)`` is a valid change of basis, but onto no tabulated setting."""
    with pytest.raises(KeyError):
        hall_setting(written)
    with pytest.raises(ValueError, match="names no known space-group setting"):
        _declared_settings({"space_group_name_hall": written})


def _sg4_cif(tmp_path: Path, hall: str, operations: list[str] | tuple[str, ...] | None) -> Path:
    loop = "" if operations is None else "loop_\n_space_group_symop_operation_xyz\n" + "\n".join(operations) + "\n"
    path = tmp_path / "hall.cif"
    path.write_text(
        "data_x\n_cell_length_a 5.0\n_cell_length_b 6.0\n_cell_length_c 7.0\n"
        "_cell_angle_alpha 90\n_cell_angle_beta 90\n_cell_angle_gamma 90\n"
        f"_space_group_name_Hall '{hall}'\n" + loop + "loop_\n_atom_site_label\n_atom_site_type_symbol\n"
        "_atom_site_fract_x\n_atom_site_fract_y\n_atom_site_fract_z\n"
        "Si1 Si 0.1 0.2 0.3\n",
        encoding="utf-8",
    )
    return path


def test_a_cif_with_a_suffixed_hall_symbol_and_matching_operations_loads(tmp_path: Path) -> None:
    """``P 2yb (z,x,y)`` relabels the b-axis screw onto c: setting 4:c (``P 2c``)."""
    path = _sg4_cif(tmp_path, "P 2yb (z,x,y)", ["x,y,z", "-x,-y,z+1/2"])
    assert cif_setting(load(str(path), raw=True)["blocks"][0]).setting == "4:c"
    assert load(str(path)).spacegroup.setting == "4:c"


def test_a_cif_whose_operations_contradict_the_suffixed_hall_symbol_raises(tmp_path: Path) -> None:
    path = _sg4_cif(tmp_path, "P 2yb (z,x,y)", ["x,y,z", "-x,y+1/2,-z"])
    with pytest.raises(ValueError, match="the Hall symbol 'P 2yb \\(z,x,y\\)'.*contradicts itself"):
        load(str(path))


def test_a_malformed_suffix_is_an_unknown_hall_symbol(tmp_path: Path) -> None:
    path = _sg4_cif(tmp_path, "P 2yb (z,x)", ["x,y,z", "-x,-y,z+1/2"])
    with pytest.raises(ValueError, match="names no known space-group setting"):
        load(str(path))


def test_repair_generates_operations_from_a_suffixed_hall_symbol(
    tmp_path: Path, caplog: pytest.LogCaptureFixture
) -> None:
    path = _sg4_cif(tmp_path, "P 2yb (z,x,y)", None)
    with pytest.raises(ValueError, match="no symmetry operations"):
        load(str(path))
    with caplog.at_level(logging.WARNING, logger="httk.atomistic.io.cif.cif_parser"):
        structure = load(str(path), repair=True)
    assert structure.spacegroup.setting == "4:c"
    assert "Hall symbol 'P 2yb (z,x,y)' (setting '4:c')" in caplog.records[0].getMessage()


def test_a_same_type_hall_symbol_contradicting_the_operations_raises(tmp_path: Path) -> None:
    """``I -2yc`` declared on ``C -2yc`` operations: both are type 9, but different settings."""
    operations = tuple(
        operation.wrapped().to_xyz() for operation in Spacegroup.from_hall_entry("c_-2yc").symmetry_operations
    )
    path = _sg4_cif(tmp_path, "I -2yc", operations)
    with pytest.raises(ValueError, match="contradicts itself"):
        load(str(path))


def test_repair_refuses_a_suffix_onto_no_tabulated_setting(tmp_path: Path) -> None:
    with pytest.raises(ValueError, match="no symmetry operations"):
        load(str(_sg4_cif(tmp_path, "P 2yb (0 0 1)", None)), repair=True)
