def _reference(structure: Any, site: int) -> FracVector:
    wyckoff = structure.wyckoff_sites[site]
    return structure.spacegroup.wyckoff_position(wyckoff.wyckoff).representative.coordinate(wyckoff.free_params)


def _key(p: tuple[F, ...], q: tuple[F, ...]) -> tuple[F, ...]:
    """An unordered pair of exact points modulo lattice translations."""
    return min(
        tuple(x - s for x, s in zip((*a, *b), [x.numerator // x.denominator for x in a] * 2, strict=True))
        for a, b in ((p, q), (q, p))
    )


def _closure(generators: list[tuple[F, ...]]) -> list[tuple[F, ...]]:
    """The finite group of translations modulo one generated by ``generators``."""
    found = {(F(0), F(0), F(0))}
    frontier = list(found)
    while frontier:
        current = frontier.pop()
        for g in generators:
            moved = tuple((a + b) % 1 for a, b in zip(current, g, strict=True))
            if moved not in found:
                found.add(moved)
                frontier.append(moved)
    return sorted(found)


def _own_pairs(structure: Any) -> set[tuple[F, ...]]:
    """Every bonded atom pair of the network in the structure's own cell, modulo its lattice.

    Coordinates are the structure's own fractional coordinates, so the pairs are the Cartesian
    pairs of its frame read in its cell basis.
    """
    transform = structure.transform
    pairs = set()
    for bond in structure.bonds.pairs:
        p, q = _reference(structure, bond.site), bond.operation.apply(_reference(structure, bond.partner))
        for g in structure.spacegroup.symmetry_operations:
            a, b = transform.to_setting(g.apply(p)), transform.to_setting(g.apply(q))
            for coset in transform.lattice_cosets():
                pairs.add(_key(tuple((a + coset).to_fractions()), tuple((b + coset).to_fractions())))
    return pairs


def _atoms(structure: Any) -> set[tuple[Any, ...]]:
    view = UnitcellStructureView(structure)
    chemistry = {species.name: species.chemical_symbols for species in view.species}
    return {
        (chemistry[name], tuple(x % 1 for x in point))
        for name, point in zip(view.species_at_sites, view.sites.reduced_coords.to_fractions(), strict=True)
    }


def _isometries(source: Any, result: Any) -> Iterator[tuple[FracVector, tuple[F, ...]]]:
    """Yield every exact ``f -> A f + t`` from ``source``'s own cell onto ``result``'s that is an isometry
    mapping the atoms onto the atoms (column convention).

    The columns of ``A`` are crystal translations of ``result`` (lattice plus centring, entries up to 3)
    whose metric matches ``source``'s cell; the map is verified exactly, metric and atoms.
    """
    source_metric, result_metric = source.cell.metric(), result.cell.metric()
    gs, gr = source_metric.to_floats(), result_metric.to_floats()
    centring = [
        tuple(operation.vector.to_fractions())
        for operation in (AffineOperation(xyz) for xyz in result.space_group_symmetry_operations_xyz)
        if operation.matrix == FracVector.eye((3, 3))
    ]
    vectors = [
        tuple(n + c for n, c in zip(ns, cs, strict=True))
        for ns in itertools.product(range(-3, 4), repeat=3)
        for cs in centring
    ]

    def dot(u: tuple[F, ...], v: tuple[F, ...]) -> float:
        return sum(float(u[i]) * gr[i][j] * float(v[j]) for i in range(3) for j in range(3))

    columns = [[v for v in vectors if abs(dot(v, v) - gs[k][k]) < 1e-9] for k in range(3)]
    source_atoms, result_atoms = _atoms(source), _atoms(result)
    anchor = min(source_atoms)
    for a, b, c in itertools.product(*columns):
        if abs(dot(a, b) - gs[0][1]) > 1e-9 or abs(dot(a, c) - gs[0][2]) > 1e-9 or abs(dot(b, c) - gs[1][2]) > 1e-9:
            continue
        A = FracVector([[a[r], b[r], c[r]] for r in range(3)])
        if A.det() == 0 or SurdVector(A.T()) * result_metric * SurdVector(A) != source_metric:
            continue
        cosets = _closure([tuple(A.T()[k].to_fractions()) for k in range(3)])
        for symbols, point in result_atoms:
            if symbols != anchor[0]:
                continue
            t = tuple((FracVector(point) - FracVector(anchor[1]) * A.T()).to_fractions())
            moved = {
                (s, tuple((x + y) % 1 for x, y in zip((FracVector(p) * A.T() + FracVector(t)).to_fractions(), shift)))
                for s, p in source_atoms
                for shift in cosets
            }
            if moved == result_atoms:
                yield A, t


def _moved_pairs(pairs: set[tuple[F, ...]], A: FracVector, t: tuple[F, ...]) -> set[tuple[F, ...]]:
    """Map pairs (modulo one lattice) by ``f -> A f + t`` and key them modulo the other lattice.

    The images of the first lattice's translations that are not translations of the second
    give further pairs.
    """
    cosets = _closure([tuple(A.T()[k].to_fractions()) for k in range(3)])
    moved = set()
    for key in pairs:
        p, q = (tuple((FracVector(x) * A.T() + FracVector(t)).to_fractions()) for x in (key[:3], key[3:]))
        for c in cosets:
            moved.add(_key(tuple(a + b for a, b in zip(p, c)), tuple(a + b for a, b in zip(q, c))))
    return moved


def _same_network(source: Any, result: Any) -> bool:
    """Whether ``result``'s network is ``source``'s, mapped pair by pair through an isometry of the two.

    The pairs are compared both ways, modulo each structure's own lattice, so cells of different
    size compare correctly: a translation one cell has and the other lacks is checked too.
    """
    source_pairs, result_pairs = _own_pairs(source), _own_pairs(result)
    for A, t in _isometries(source, result):
        inverse = A.inv()
        back = tuple((-(FracVector(t) * inverse.T())).to_fractions())
        if (
            _moved_pairs(source_pairs, A, t) == result_pairs
            and _moved_pairs(result_pairs, inverse, back) == source_pairs
        ):
            return True
    return False


