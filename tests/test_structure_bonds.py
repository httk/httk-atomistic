def _nearest_bonds(
    spacegroup: Spacegroup, basis: Any, sites: list[WyckoffSite], pairs: list[tuple[int, int]]
) -> list[SiteBond]:
    """For each site pair, the bond from the first reference atom to the nearest image of the second."""
    cell = SurdVector(basis).to_floats()
    bonds = []
    for i, j in pairs:
        p = spacegroup.wyckoff_position(sites[i].wyckoff).representative.coordinate(sites[i].free_params)
        q = spacegroup.wyckoff_position(sites[j].wyckoff).representative.coordinate(sites[j].free_params)
        best = None
        for g in spacegroup.symmetry_operations:
            for n in itertools.product(range(-2, 3), repeat=3):
                op = AffineOperation(g.matrix, g.vector + FracVector(n))
                d = [float(x) for x in (op.apply(q) - p).to_fractions()]
                cart = [sum(d[k] * cell[k][axis] for k in range(3)) for axis in range(3)]
                length = sum(x * x for x in cart)
                if length > 1e-9 and (best is None or length < best[0] - 1e-9):
                    best = (length, op)
        assert best is not None
        bonds.append(SiteBond(i, j, best[1]))
    return bonds


def _diamond(setting: str) -> ASUStructure:
    spacegroup = Spacegroup.from_setting(setting)
    basis = [[F(7, 2), 0, 0], [0, F(7, 2), 0], [0, 0, F(7, 2)]]
    sites = [WyckoffSite("a", (), "C")]
    return ASUStructure(basis, spacegroup, sites, [C], bonds=_nearest_bonds(spacegroup, basis, sites, [(0, 0)]))


def _chain(*, left: bool = False) -> ASUStructure:
    """A P2_1 helix of one atom along b, in a right-handed cell or (``left``) the negated one."""
    spacegroup = Spacegroup.standard(4)
    basis = [[4, 0, 0], [0, 3, 0], [1, 0, 6]]
    sites = [WyckoffSite("a", (F(1, 10), F(1, 5), F(3, 10)), "C")]
    (bond,) = _nearest_bonds(spacegroup, basis, sites, [(0, 0)])
    if not left:
        return ASUStructure(basis, spacegroup, sites, [C], bonds=[bond])
    # the same crystal: basis -B, coordinates -f, the operation conjugated by the inversion
    negate = AffineOperation(((-1, 0, 0), (0, -1, 0), (0, 0, -1)))
    flipped = [WyckoffSite("a", (-F(1, 10), -F(1, 5), -F(3, 10)), "C")]
    operation = negate * bond.operation * negate
    return ASUStructure(
        [[-x for x in row] for row in basis], spacegroup, flipped, [C], bonds=[SiteBond(0, 0, operation)]
    )


def _monoclinic(spacegroup: Spacegroup, basis: Any) -> ASUStructure:
    """Si on a general position and O on an inversion centre of a P 2_1/c setting, Si-O and Si-Si bonded."""
    general = next(w for w in spacegroup.wyckoff if w.free_count == 3).letter
    centre = next(w for w in spacegroup.wyckoff if w.free_count == 0).letter
    sites = [WyckoffSite(general, (F(1, 8), F(2, 7), F(3, 11)), "Si"), WyckoffSite(centre, (), "O")]
    bonds = _nearest_bonds(spacegroup, basis, sites, [(0, 1), (0, 0)])
    return ASUStructure(basis, spacegroup, sites, [SI, O], bonds=bonds)


def _in_standard_setting(structure: ASUStructure) -> ASUStructure:
    """The same crystal in its standard setting, sites and bonds found anew (not carried)."""
    transform = structure.spacegroup.transform_from_standard
    standard = structure.spacegroup.standard_setting()
    basis = transform.basis_to_standard(structure.cell.basis)
    sites = []
    for site in structure.wyckoff_sites:
        own = structure.spacegroup.wyckoff_position(site.wyckoff).representative.coordinate(site.free_params)
        identified = standard.identify_wyckoff(transform.to_standard(own).normalize())
        assert identified is not None
        sites.append(WyckoffSite(identified[0].letter, identified[1], site.species))
    pairs = sorted({(b.site, b.partner) for b in (structure.bonds.pairs if structure.bonds else ())})
    return ASUStructure(basis, standard, sites, structure.species, bonds=_nearest_bonds(standard, basis, sites, pairs))


def _p21n() -> ASUStructure:
    return _monoclinic(Spacegroup.from_hm_entry("P 1 21/n 1"), [[5, 0, 0], [0, 6, 0], [-1, 0, 7]])


