@pytest.mark.parametrize("kind", [ASUStructure, FundamentalDomainStructure])
def test_records_round_trip_the_network_and_keep_the_identity_without_one(kind: type[Any]) -> None:
    diamond = _diamond("227:2")
    args = (diamond.cell, diamond.spacegroup, diamond.wyckoff_sites, [C])
    values = (kind(*args), kind(*args, bonds=[]), kind(*args, bonds=diamond.bonds))
    records = [_domain_structure_record_from_value(value) for value in values]
    record_type = ASUStructureRecord if kind is ASUStructure else FundamentalDomainStructureRecord
    assert all(type(record) is record_type for record in records)
    assert [record.bonds for record in records[:2]] == [None, ()]
    assert len({content_id(record) for record in records}) == 3
    for value, record in zip(values, records, strict=True):
        assert content_id(record) == content_id(value)
        assert _domain_structure_from_record(record) == value
        record_type.__httk_validate__(record)
    # a stored network must be the normal one: another spelling of the same orbit is rejected
    other = next(member.operation for member in _diamond_members(diamond) if member != diamond.bonds.pairs[0])
    spelled = SiteBondRecord(0, 0, other.matrix, tuple(other.vector.to_fractions()))
    with pytest.raises(ValueError, match="normalized"):
        record_type.__httk_validate__(replace(records[2], bonds=(spelled,)))


def test_a_store_keeps_no_network_an_empty_network_and_a_network_apart() -> None:
    pytest.importorskip("sqlalchemy")
    pytest.importorskip("httk.store")
    from httk.store import Backend, EntryIdScheme, SqlStore

    diamond = _diamond("227:2")
