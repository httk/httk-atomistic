CARRIERS = {
    "declared": lambda s: canonicalize(s, symmetry="declared"),
    "detect": canonicalize,
    "protostructure": canonical_asu_protostructure,
    "assignments": lambda s: canonical_asu_protostructure_assignments(s)[0],
    "conventional": lambda s: conventional_cell(s).asu,
}


@pytest.mark.parametrize("carrier", sorted(CARRIERS))
@pytest.mark.parametrize(
    "name",
    [
        "diamond 227:1",
        "chain",
        "left chain",
        "P 1 21/n 1",
        "P 4_2/n b c 133:1",
        "R -3 m 166:R",
        "P1 supercell chain",
        "P1 primitive diamond",
    ],
)
def test_every_canonicaliser_carries_the_network(name: str, carrier: str) -> None:
    source = {
        "diamond 227:1": lambda: _diamond("227:1"),
        "chain": _chain,
        "left chain": lambda: _chain(left=True),
        "P 1 21/n 1": _p21n,
        "P 4_2/n b c 133:1": lambda: _p42nbc("133:1"),
        "R -3 m 166:R": _rhombohedral,  # the standard setting's cell is three times larger
        "P1 supercell chain": lambda: _p1_pair(chain=True),  # the canonical cell is half as large
        "P1 primitive diamond": _primitive_diamond,  # recognized face-centred: four times larger
    }[name]()
    result = CARRIERS[carrier](source)
    assert result.bonds is not None
    assert _same_network(source, result)


@pytest.mark.parametrize("carrier", sorted(CARRIERS))
def test_a_network_without_the_target_s_translations_is_never_extended(carrier: str) -> None:
    # a dimer in a doubled P1 cell: the half-cell translation of the atoms does not keep the bonds,
    # so a smaller cell can only drop the network, never turn the dimer into a chain
    source = _p1_pair(chain=False)
    result = CARRIERS[carrier](source)
    assert result.bonds is None or _same_network(source, result)


def test_class_symmetry_that_does_not_keep_the_bonds_is_refused() -> None:
    # Fe2+ at 0, Fe3+ at 1/2, O at 1/4 and 3/4: the class structure halves the cell (P m m m), and an
    # O-Fe2+-O trimer is not invariant under the half-cell translation
    fe2, fe3 = Species("Fe2", ("Fe",), (1,), charges=(2,)), Species("Fe3", ("Fe",), (1,), charges=(3,))
    sites = [
        WyckoffSite("a", (0, 0, 0), "Fe2"),
        WyckoffSite("a", (F(1, 2), 0, 0), "Fe3"),
        WyckoffSite("a", (F(1, 4), 0, 0), "O"),
        WyckoffSite("a", (F(3, 4), 0, 0), "O"),
    ]
    bonds = [SiteBond(0, 2, ONE), SiteBond(0, 3, AffineOperation(ONE.matrix, (-1, 0, 0)))]
    trimer = ASUStructure([[7, 0, 0], [0, 4, 0], [0, 0, 5]], 1, sites, [fe2, fe3, O], bonds=bonds)
    with pytest.raises(ValueError, match="not invariant"):
        Protonetstructure.from_asu(trimer)
    # with the Fe3+-O bonds too it is the chain of the class structure
