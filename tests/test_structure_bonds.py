def test_tied_frames_are_told_apart_by_the_network() -> None:
    # C at 0 and O at u and at its image under the two-fold axis along c: bonding C to either O is
    # the same crystal, so both spellings canonicalize to one value
    sites = [
        WyckoffSite("a", (0, 0, 0), "C"),
        WyckoffSite("a", (F(1, 5), F(3, 10), F(1, 10)), "O"),
        WyckoffSite("a", (F(4, 5), F(7, 10), F(1, 10)), "O"),
    ]
    cell = [[5, 0, 0], [0, 6, 0], [0, 0, 7]]
    first = ASUStructure(cell, 1, sites, [C, O], bonds=[SiteBond(0, 1, ONE)])
    second = ASUStructure(cell, 1, sites, [C, O], bonds=[SiteBond(0, 2, AffineOperation(ONE.matrix, (-1, -1, 0)))])
    for name, carrier in CARRIERS.items():
        if name != "conventional":  # a change of setting, not a canonicalizer
            assert carrier(first) == carrier(second)
    assert canonicalize(first, symmetry="declared").bonds is not None
    # the same two O on 2i of P-1: the declared canonicalization ties above P1 too
    centred = [
        WyckoffSite("a", (), "C"),
        WyckoffSite("i", sites[1].free_params, "O"),
        WyckoffSite("i", sites[2].free_params, "O"),
    ]
    first = ASUStructure(cell, 2, centred, [C, O], bonds=[SiteBond(0, 1, ONE)])
    second = ASUStructure(cell, 2, centred, [C, O], bonds=[SiteBond(0, 2, AffineOperation(ONE.matrix, (-1, -1, 0)))])
    declared = [canonicalize(value, symmetry="declared") for value in (first, second)]
    assert declared[0] == declared[1] and declared[0].bonds is not None


