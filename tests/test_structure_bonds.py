    assert ProtonettypeView(structure).unview() == anonymous == ProtonettypeView(value).unview()
    assert canonical_protonetstructure(structure) == canonical_protonetstructure(value)
    assert canonical_protonettype(structure) == canonical_protonettype(anonymous)
